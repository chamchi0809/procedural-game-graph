import { generateLevel, DEFAULT_PARAMS } from '../src/core/generate';
import { GameRuntime } from '../src/game/runtime';
import { Autopilot } from '../src/game/bot';
const level = generateLevel({ ...DEFAULT_PARAMS, seed: `bot-8`, locations: 9 });
const rt = new GameRuntime(level);
const bot = new Autopilot(rt);
let t = 0;
while (t < 300 && bot.step(1 / 30)) t += 1 / 30;
const g = rt.byId.get(bot.current!)!;
console.log(bot.current, g.lock, "player", rt.player, "trail", (rt as any).trail.length, "path", (bot as any).path, "side", rt.sideOf(g.id));
for (const e of level.graph.edges.filter(e => e.to === g.id)) console.log(' dep', e.from, e.kind, rt.done.has(e.from), rt.followers.get(e.from));
console.log('order idx', level.solution.indexOf(g.id), level.solution.slice(0, level.solution.indexOf(g.id)+1).join(' '));
const tr = (rt as any).trail as {x:number,y:number}[];
console.log('trail tail', tr.slice(-6));
const door = level.world.doors[g.id];
console.log('door', door.cx, door.cy);
for (let i = 0; i < 30; i++) bot.step(1/30);
console.log('creature after', rt.followers.get('follower:L5:0'));
console.log('walls near creature->player', level.world.walls.filter(w => Math.min(Math.hypot(w.ax+28.5, w.ay-5), Math.hypot(w.bx+28.5,w.by-5)) < 3).length);
